"""Mission / workflow mode: one sentence -> a scripted sequence of safe actions.

Workflows live in data/workflows.json (created with defaults on first use), so
you can edit them without touching code. Only a small allow-list of actions is
supported and workflows are never generated by the LLM, so this cannot do
anything you did not write down.
"""
import json
import os
import re
import time
import webbrowser

from ..core.hooks import emit

